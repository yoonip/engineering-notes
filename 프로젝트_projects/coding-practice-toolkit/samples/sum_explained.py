# 시작 예제: 첫 수 N 다음에 오는 N개 정수의 합을 출력합니다.
# 입력 예: 5 / 1 2 3 4 5 → 출력 15. /는 줄바꿈을 뜻합니다.
# F5 또는 Ctrl+F5에서는 이 폴더의 input.txt가 자동으로 표준 입력이 됩니다.
# 키보드 모드에서는 read()가 입력 끝을 기다립니다. Windows에서는 마지막 줄 뒤 Ctrl+Z, Enter로 EOF를 보냅니다.
import sys  # 표준 입력(stdin) 등 Python 실행 환경을 다루는 모듈입니다.

# buffer.read()는 입력의 모든 bytes를 EOF까지 읽습니다. split()은 공백·줄바꿈으로 토큰을 나눕니다.
# map(int, ...)가 각 토큰을 정수로 바꾸고, list(...)가 그 결과를 인덱스로 접근할 목록에 저장합니다.
# '5\n1 2 3 4 5\n'을 읽으면 data는 [5, 1, 2, 3, 4, 5]입니다.
data = list(map(int, sys.stdin.buffer.read().split()))
if data:  # 빈 입력이면 data[0]에 접근하지 않습니다. 정상 문제 입력에는 N이 있습니다.
    n = data[0]  # 첫 번째 수는 더할 값이 아니라 뒤에 오는 정수의 개수입니다.
    # a[start:end]는 start부터 end 직전까지 선택합니다. 따라서 1:1+n은 뒤의 N개 값입니다.
    # sum(...)은 선택한 값들의 합을 반환하고, print(...)는 그 답과 줄바꿈을 출력합니다.
    print(sum(data[1:1 + n]))

# 확인: N=0이면 빈 목록의 합 0, 음수는 부호를 그대로 더합니다.
# 입력 전체를 저장하므로 시간 O(N), 메모리 O(N). 잘못된 입력의 개수 일치는 검사하지 않는 간단한 샘플입니다.
