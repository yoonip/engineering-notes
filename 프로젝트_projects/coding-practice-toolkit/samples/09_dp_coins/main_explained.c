// 자체 창작 연습 09 · 최소 동전 개수 
// 핵심 상태: dp[x]는 금액 x를 만드는 최소 동전 개수. inf는 만들 수 없음, dp[0]=0이다.
// C11: main이 실행 시작점이다. stdio.h의 scanf/printf로 표준입출력을 사용한다.
// scanf의 %d는 int, %lld는 long long이다. 정수 변수 앞 &는 저장할 주소를 전달한다.
// 문자열 배열 이름은 첫 원소의 주소로 전달된다. 문자열에는 끝의 널 문자 공간이 필요하다.

#include <stdio.h>
int coin[100], dp[10001];
int main(void) {
    // 목표는 최대 10000이다. 만들 수 있다면 양의 금액 동전은 많아도 10000개면 충분하다.
    // 따라서 10001을 불가능 표시 inf로 쓸 수 있다. 실제 정답과 구분된다.
    // coin은 최대 100종, dp는 금액 0~10000까지 저장하는 배열이다.
    int n, k, inf = 10001;
    scanf("%d %d", &n, &k);
    for (int i = 0; i < n; ++i) scanf("%d", &coin[i]);
    dp[0] = 0;
    // dp[0]=0을 출발점으로 두고 작은 금액부터 dp를 채운다.
    // 새 금액의 시작 상태를 inf로 둔 뒤 모든 마지막 동전 후보를 확인한다.
    // x에서 동전 c를 마지막에 썼다면 이전 금액 x-c의 최소 개수에 1을 더한다.
    for (int x = 1; x <= k; ++x) {
        dp[x] = inf;
        for (int i = 0; i < n; ++i) {
            int c = coin[i];
            // c<=x를 먼저 확인해 음수 배열 위치 x-c를 읽지 않는다.
            // &&는 왼쪽이 거짓이면 오른쪽을 평가하지 않는 단락 평가다.
            // 불가능 상태 inf에 1을 더한 후보는 현재 inf보다 작지 않아 선택되지 않는다.
            if (c <= x && dp[x-c] + 1 < dp[x])
                dp[x] = dp[x-c] + 1;  // 동전 c 하나를 마지막에 추가한 후보가 더 좋다.
        }
    }
    printf("%d\n", dp[k] == inf ? -1 : dp[k]);
    return 0;
}

// 복잡도: 시간 O(NK), 공간 O(N+K).
// 마지막 경계 확인:
// - 동전은 무제한 사용 가능하다. 한 번씩만 쓰는 문제와 다르다.
// - dp를 0으로 채우면 불가능한 금액도 가능하다고 처리된다.
// - x-c가 음수인 후보는 건너뛴다.
// - INF=K+1도 가능하지만 여기서는 제한에 맞춰 10001을 쓴다.
