// 자체 창작 연습 02 · 가장 자주 나온 측정값 
// 핵심 상태: freq[x]는 값 x의 등장 횟수, best는 지금까지 가장 많이 나온 후보 값이다.
// C++17: main이 실행 시작점이다. cin/cout은 변수 타입에 맞게 입력·출력을 처리한다.
// sync_with_stdio(false), cin.tie(nullptr)는 많은 입출력의 불필요한 동기화·flush를 줄인다.
// 이 설정을 사용한 뒤 scanf와 cin을 섞지 않는 방식으로 연습한다.

#include <iostream>
using namespace std;
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n, x, best = 0;
    // {}는 모든 칸을 0으로 초기화한다. 빈도는 0에서 세기 시작해야 한다.
    // freq의 1001칸이 각각 값 0~1000의 횟수를 담는다.
    // 고정된 작은 정수 범위라서 map 없이 배열만으로 빠르고 간단히 처리한다.
    int freq[1001] = {};
    cin >> n;
    // 입력 x 하나를 읽고 freq[x]만 1 증가시킨다.
    // freq는 원본 입력의 순서가 아니라 값별 횟수를 저장한다.
    // 입력값을 인덱스로 쓰므로 반드시 문제의 값 범위를 먼저 확인한다.
    for (int i = 0; i < n; ++i) {
        cin >> x;
        ++freq[x];  // 해당 값의 횟수만 증가시킨다.
    }
    // 작은 값부터 검사하며 엄격히 더 많은 빈도에서만 best를 바꾼다.
    // 예제에서는 1과 3이 각 세 번인데 1을 먼저 골라 계속 유지한다.
    // 최종 출력은 선택한 값과 그 값의 횟수 두 개다.
    for (int x = 1; x <= 1000; ++x)
        if (freq[x] > freq[best]) best = x;
    cout << best << ' ' << freq[best] << '\n';
}

// 복잡도: 시간 O(N+1001). C/C++ 추가 공간 O(1001); Python은 전체 입력 파싱 때문에 O(N+1001).
