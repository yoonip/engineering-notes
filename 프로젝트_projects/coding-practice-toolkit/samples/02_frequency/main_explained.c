// 자체 창작 연습 02 · 가장 자주 나온 측정값 
// 핵심 상태: freq[x]는 값 x의 등장 횟수, best는 지금까지 가장 많이 나온 후보 값이다.
// C11: main이 실행 시작점이다. stdio.h의 scanf/printf로 표준입출력을 사용한다.
// scanf의 %d는 int, %lld는 long long이다. 정수 변수 앞 &는 저장할 주소를 전달한다.
// 문자열 배열 이름은 첫 원소의 주소로 전달된다. 문자열에는 끝의 널 문자 공간이 필요하다.

#include <stdio.h>
// 배열 인덱스 0~1000이 각각 실제 값 0~1000을 뜻한다.
// 1000도 저장해야 하므로 길이는 1001이다.
// 전역변수 배열은 C에서 자동으로 0으로 초기화된다. 지역 배열이면 초기화를 명시해야 한다.
int freq[1001];
int main(void) {
    int n, x, best = 0;
    scanf("%d", &n);
    // 입력 숫자 x를 배열의 위치로 사용해 해당 칸의 횟수만 1 늘린다.
    // 예제에서 값 1은 세 번 들어오므로 freq[1]=3이 된다.
    // 이 입력의 값 범위가 0~1000이라는 조건이 배열 접근의 안전성을 보장한다.
    for (int i = 0; i < n; ++i) {
        scanf("%d", &x);
        ++freq[x];  // 값 x가 한 번 더 등장했다.
    }
    // best=0을 첫 후보로 두고 나머지 값들을 작은 순서대로 검사한다.
    // 새 횟수가 더 클 때만 갱신한다. 같은 횟수에서는 앞서 선택한 작은 값이 남는다.
    // >=로 바꾸면 동점에서 큰 값을 골라 문제의 조건을 어기게 된다.
    for (int x = 1; x <= 1000; ++x)
        if (freq[x] > freq[best]) best = x;
    printf("%d %d\n", best, freq[best]);
    return 0;
}

// 복잡도: 시간 O(N+1001). C/C++ 추가 공간 O(1001); Python은 전체 입력 파싱 때문에 O(N+1001).
// 마지막 경계 확인:
// - 동점 조건에서 >=로 갱신하면 더 큰 값이 선택된다.
// - freq 배열 크기는 1001이어야 값 1000을 저장할 수 있다.
// - 빈도 배열은 처음 0으로 초기화한다.
