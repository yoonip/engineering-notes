# 자체 창작 연습 02 · 가장 자주 나온 측정값 
# 핵심 상태: freq[x]는 값 x의 등장 횟수, best는 지금까지 가장 많이 나온 후보 값이다.
# Python 3: 파일의 위에서 아래로 실행한다. 들여쓰기가 반복문·조건문·함수의 범위다.
# sys.stdin은 표준입력이다. read()는 EOF까지 읽으므로 파일 입력과 온라인 채점에 편하다.
# 터미널에 직접 붙여 넣을 때 read()가 대기하면 Windows에서 Ctrl+Z 후 Enter로 EOF를 보낸다.

import sys
data = list(map(int, sys.stdin.buffer.read().split()))
n = data[0]
# 0이 든 리스트를 1001칸 만든다. 숫자 0은 불변값이어서 이 초기화는 안전하다.
# freq[x]가 값 x의 횟수를 뜻한다. 원본 배열의 x번째 원소라는 뜻이 아니다.
# data[1:n+1]은 헤더 N을 제외한 입력값들을 고른다.
freq = [0] * 1001
for x in data[1:n + 1]:
    freq[x] += 1
best = 0
# range(1,1001)은 1부터 1000까지이며 오른쪽 끝 1001은 포함하지 않는다.
# 0은 best의 초기 후보로 이미 포함했고 나머지 값을 작은 순으로 확인한다.
# 횟수가 같은 경우에는 바꾸지 않아 작은 값이 남는다.
for x in range(1, 1001):
    if freq[x] > freq[best]:  # 동점은 갱신하지 않는다.
        best = x
print(best, freq[best])

# 복잡도: 시간 O(N+1001). C/C++ 추가 공간 O(1001); Python은 전체 입력 파싱 때문에 O(N+1001).
# 마지막 경계 확인:
# - 동점 조건에서 >=로 갱신하면 더 큰 값이 선택된다.
# - freq 배열 크기는 1001이어야 값 1000을 저장할 수 있다.
# - 빈도 배열은 처음 0으로 초기화한다.
