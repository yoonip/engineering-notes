# 평균 구하기
# 분류: 합계 / 평균
# 공개 문제 링크: https://school.programmers.co.kr/learn/courses/30/lessons/12944
# AI 작성 학습 풀이입니다. 온라인 채점 통과를 확인한 제출물이 아닙니다.

def solution(arr):
    return sum(arr) / len(arr)


