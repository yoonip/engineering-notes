// 자체 창작 연습 06 · 격자 통로의 최소 이동 
// 핵심 상태: dist[r][c]는 최소 이동 횟수이며 -1이면 미방문. 큐는 아직 이웃을 살피지 않은 칸이다.
// C11: main이 실행 시작점이다. stdio.h의 scanf/printf로 표준입출력을 사용한다.
// scanf의 %d는 int, %lld는 long long이다. 정수 변수 앞 &는 저장할 주소를 전달한다.
// 문자열 배열 이름은 첫 원소의 주소로 전달된다. 문자열에는 끝의 널 문자 공간이 필요하다.

#include <stdio.h>
// 행 개수는 최대 100이고 한 행의 문자열은 최대 100문자다.
// 각 행에는 널 종료 문자 한 칸이 필요하므로 두 번째 크기는 101이다.
// dist는 좌표별 거리표이고 queue[10000]은 최대 100×100칸을 한 번씩 저장할 공간이다.
char grid[100][101];
int dist[100][100], queue[10000];
int main(void) {
    int n, m, head = 0, tail = 0;
    int dr[4] = {-1,1,0,0}, dc[4] = {0,0,-1,1};
    scanf("%d %d", &n, &m);
    for (int r = 0; r < n; ++r) {
        scanf("%100s", grid[r]);
        for (int c = 0; c < m; ++c) dist[r][c] = -1;
    }
    // 시작칸이 통로일 때만 거리 0으로 표시하고 큐에 넣는다.
    // 시작칸이 벽이면 큐가 비어 탐색을 하지 않으므로 도착 거리도 -1로 남는다.
    // queue에는 (r,c)를 r*m+c라는 정수 하나로 저장한다. 시작 (0,0)은 0이다.
    if (grid[0][0] == '1') {
        dist[0][0] = 0;
        queue[tail++] = 0;
    }
    // head는 다음에 꺼낼 위치, tail은 다음에 넣을 위치다. head<tail이면 대기 중인 칸이 있다.
    // 먼저 넣은 칸부터 꺼내므로 같은 이동 비용의 격자에서 짧은 거리부터 처리한다.
    // 꺼낸 p를 p/m, p%m로 행·열로 복원한다. m은 열 개수다.
    while (head < tail) {
        int p = queue[head++], r = p / m, c = p % m;
        // dr,dc 네 쌍이 위·아래·왼쪽·오른쪽 이동을 뜻한다.
        // 격자 밖 좌표는 배열에 접근하기 전에 continue로 건너뛴다.
        // 벽이나 이미 방문한 칸도 제외하고 처음 보는 통로의 거리만 기록한다.
        for (int k = 0; k < 4; ++k) {
            int nr = r + dr[k], nc = c + dc[k];
            if (nr < 0 || nr >= n || nc < 0 || nc >= m)
                continue;
            if (grid[nr][nc] == '0' || dist[nr][nc] != -1)
                continue;
            // 현재 칸에서 한 번 더 이동했으므로 거리를 1 늘린다.
            // 큐에 넣는 순간 방문 표시를 해야 같은 칸이 여러 번 들어가지 않는다.
            // 끝에 도착칸 dist를 출력한다. 시작=도착인 통로의 답은 이동하지 않은 0이다.
            dist[nr][nc] = dist[r][c] + 1;
            queue[tail++] = nr * m + nc;  // 좌표를 정수로 묶어 큐 뒤에 삽입한다.
        }
    }
    printf("%d\n", dist[n - 1][m - 1]);
    return 0;
}

// 복잡도: 시간 O(NM), 공간 O(NM). 각 칸은 최대 한 번 큐에 들어가고 네 이웃을 확인한다.
// 마지막 경계 확인:
// - 벽·범위 밖·방문한 칸을 모두 제외한다.
// - 방문 표시를 큐에서 꺼낼 때 하면 중복 삽입이 생긴다.
// - 이 문제는 지나간 칸 수가 아니라 이동 횟수다. 시작 거리는 0.
// - Python list.pop(0)은 앞 원소 이동 비용이 있으므로 deque.popleft를 쓴다.
