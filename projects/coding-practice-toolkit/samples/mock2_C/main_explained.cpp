// 동전 사용 순서를 구별하지 않는 조합의 수를 구한다.
// 동전 종류를 바깥 반복으로 처리해야 같은 조합을 사용 순서별로 중복해서 세지 않는다.
// 금액은 오름차순으로 갱신하여 지금 처리 중인 동전을 여러 번 사용할 수 있게 한다.
// 입력 제한과 실행 비용: 시간 O(NK), 공간 O(N+K).

// dp[x]는 지금까지 처리한 동전 종류만으로 금액 x를 만드는 조합 수다.
// dp[0]=1은 동전을 하나도 쓰지 않는 빈 조합 하나다. K=0에서도 답은 1이다.
// mod=1,000,000,007이며 매번 나머지를 저장한다. 음수 상태나 최소 동전 수를 뜻하는 표가 아니다.

// vector는 실행 중 정해진 크기의 배열, queue는 먼저 넣은 원소를 먼저 꺼내는 큐다.
// 사용한 컨테이너와 헤더는 이 원문 그대로 따른다. 빠른 cin 설정 뒤에는 scanf와 섞지 않는다.

#include <iostream>
#include <vector>
using namespace std;
int main() {
    ios::sync_with_stdio(false); cin.tie(nullptr);
    int n,k,mod=1000000007; cin >> n >> k;
    vector<int> coin(n),dp(k+1,0);
    for(auto &c:coin) cin >> c;
    // 빈 조합이 출발점이어야 새 동전 c 하나로 금액 c를 만들 수 있다.
    // 나머지 금액은 처음에 0가지로 시작한다.
    dp[0]=1;
    // 동전 종류를 하나씩 추가한다.
    // 이전 종류들로 만들던 조합을 유지하고 현재 동전을 더 쓴 조합을 추가한다.
    // 동전 금액은 서로 다르다는 입력 조건이 있어 같은 종류가 중복 처리되지 않는다.
    for(int c:coin)
        // x는 c부터 K까지 증가한다.
        // 이미 이번 동전으로 갱신된 dp[x-c]도 쓸 수 있으므로 같은 동전을 무제한 사용한다.
        // 역순으로 돌면 각 동전을 한 번만 쓰는 다른 문제의 갱신이 된다.
        for(int x=c;x<=k;++x)
            // 금액 x-c의 각 조합에 동전 c 하나를 붙여 금액 x의 조합을 만든다.
            // C/C++은 더하기 전에 long long으로 승격하고 나머지를 취한 뒤 int로 저장한다.
            // Python은 정수가 자동 확장되지만 결과 크기를 제한하고 규칙을 지키기 위해 나머지를 취한다.
            dp[x]=(int)(((long long)dp[x]+dp[x-c])%mod); // 기존 조합 수 + 동전 c를 한 개 더 붙인 조합 수의 나머지다.
    cout << dp[k] << '\n';
}

// 손으로 확인: K=5, 동전1 처리 → dp[0..5]=1,1,1,1,1,1
// 손으로 확인: 동전2 처리 → 1,1,2,2,3,3
// 손으로 확인: 동전5 처리 → 1,1,2,2,3,4
// 손으로 확인: 조합: 1×5 / 1×3+2 / 1+2×2 / 5
// 완성 후 확인: 조합과 순열을 구분한다.
// 완성 후 확인: 금액 x는 오름차순이어야 동전 무제한 사용이 가능하다.
// 완성 후 확인: mod 연산은 갱신할 때마다 수행한다.
