// 자체 창작 연습 01 · 숫자 기록의 합 
// 핵심 상태: total은 지금까지 읽은 숫자의 합, x는 이번에 읽은 숫자, n은 숫자 개수다.
// C11: main이 실행 시작점이다. stdio.h의 scanf/printf로 표준입출력을 사용한다.
// scanf의 %d는 int, %lld는 long long이다. 정수 변수 앞 &는 저장할 주소를 전달한다.
// 문자열 배열 이름은 첫 원소의 주소로 전달된다. 문자열에는 끝의 널 문자 공간이 필요하다.

#include <stdio.h>
int main(void) {
    int n;
    // 합은 최대 2×10^14까지 갈 수 있다. 보통의 32비트 int 범위를 넘는다.
    // long long에 합과 입력값을 저장하고 total의 시작값을 0으로 둔다.
    // 초기화하지 않은 지역변수 값으로 더하기를 시작하면 올바른 결과를 얻을 수 없다.
    long long x, total = 0;
    // scanf는 입력을 읽어 지정한 변수에 저장한다. %d는 int 입력 형식이다.
    // &n은 n의 주소다. 값을 바꿔 저장할 위치를 함수에 전달하는 표현이다.
    // 문제의 유효한 입력에서는 첫 숫자가 개수 N이며 이 숫자는 합에 포함하지 않는다.
    scanf("%d", &n);
    // i=0,1,...,n-1로 총 n번 반복한다. i<n은 배열에서도 자주 쓰는 경계다.
    // 이번 숫자를 %lld로 long long x에 읽은 뒤 total에 한 번 더한다.
    // 예제 3,-2,7,0,4에서 total은 0→3→1→8→8→12로 변한다.
    for (int i = 0; i < n; ++i) {
        scanf("%lld", &x);
        total += x;  // 지금까지의 합에 이번 값 x를 더한다.
    }
    printf("%lld\n", total);
    return 0;
}

// 복잡도: 시간 O(N). C/C++는 입력을 즉시 더해 추가 공간 O(1); Python 예제는 전체 입력 파싱으로 O(N).
// 마지막 경계 확인:
// - C에서 long long 입력은 %lld, 출력도 %lld.
// - 입력 N을 합에 포함하지 않는다.
// - 출력에 설명 문장을 붙이지 않는다.
