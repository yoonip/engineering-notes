// 자체 창작 연습 05 · 괄호 짝 검사 
// 핵심 상태: stack/st에는 아직 닫히지 않은 여는 괄호를 저장한다. top 또는 길이가 스택 크기다.
// C11: main이 실행 시작점이다. stdio.h의 scanf/printf로 표준입출력을 사용한다.
// scanf의 %d는 int, %lld는 long long이다. 정수 변수 앞 &는 저장할 주소를 전달한다.
// 문자열 배열 이름은 첫 원소의 주소로 전달된다. 문자열에는 끝의 널 문자 공간이 필요하다.

#include <stdio.h>
// s는 입력 문자열이고 stack은 여는 괄호를 쌓는 저장소다.
// 문자열 최대 길이 100000에 끝 표시 널 문자 한 칸을 더해 100001칸이 필요하다.
// scanf의 %100000s는 최대 읽을 문자 수를 제한한다. 배열 s는 첫 주소로 전달되어 &s를 쓰지 않는다.
char s[100001], stack[100001];
int main(void) {
    int top = 0, ok = 1;
    scanf("%100000s", s);
    // s[i]가 널 문자 0이 될 때 반복을 끝낸다. 널 문자는 실제 괄호가 아니다.
    // 여는 괄호는 stack[top]에 넣고 top을 늘린다. 닫는 괄호는 top을 줄여 하나 꺼낸 효과를 낸다.
    // 빈 스택에서 닫는 괄호가 나오면 앞에 짝이 없으므로 즉시 실패한다.
    for (int i = 0; s[i]; ++i) {
        if (s[i] == '(') stack[top++] = '(';  // 저장 후 top을 1 증가시킨다.
        else if (top == 0) { ok = 0; break; }
        else --top;
    }
    // 끝까지 읽었어도 여는 괄호가 남으면 올바르지 않다.
    // 중간에 실패하지 않았음과 끝에 비어 있음 두 조건을 모두 만족해야 YES다.
    // 괄호 총 개수가 같다는 것만으로는 부족하다. )(는 첫 문자에서 실패한다.
    if (top != 0) ok = 0;
    puts(ok ? "YES" : "NO");
    return 0;
}

// 복잡도: 시간 O(S), 공간 O(S). S는 문자열 길이.
// 마지막 경계 확인:
// - 끝에 남은 여는 괄호도 검사한다.
// - 스택이 빈 상태에서 pop하지 않는다.
// - 여는 괄호 수와 닫는 괄호 수만 같다고 올바른 것은 아니다: )(는 NO.
