// 시작칸에서 한 번 BFS를 수행해 모든 통로의 최소 이동 횟수를 계산한다.
// 그 거리표를 탈출구 K개에 재사용한다. 탈출구마다 다시 BFS를 하면 같은 일을 K번 하게 된다.
// 모든 이동 비용이 1이므로 먼저 방문한 칸의 거리가 최소다. 시작 거리 0은 이동 횟수 기준이다.
// 입력 제한과 실행 비용: 시간 O(NM+K), 공간 O(NM).

// g는 0/1 격자, d[r][c]는 최소 이동 횟수이며 -1은 아직 도달하지 못한 상태다.
// dr와 dc는 상하좌우 변화량이다. best와 idx의 -1은 선택 가능한 탈출구가 없다는 표시다.
// C 큐의 h는 읽을 위치, t는 다음 저장 위치다. 한 칸을 한 번 넣어 최대 N×M칸이 필요하다.

// vector는 실행 중 정해진 크기의 배열, queue는 먼저 넣은 원소를 먼저 꺼내는 큐다.
// 사용한 컨테이너와 헤더는 이 원문 그대로 따른다. 빠른 cin 설정 뒤에는 scanf와 섞지 않는다.

#include <iostream>
#include <vector>
#include <string>
#include <queue>
#include <utility>
using namespace std;
int main() {
    ios::sync_with_stdio(false); cin.tie(nullptr);
    int n,m,k; cin >> n >> m >> k;
    vector<string> g(n); for(auto &s:g) cin >> s;
    vector<vector<int>> d(n,vector<int>(m,-1));
    queue<pair<int,int>> q;
    int dr[4]={-1,1,0,0},dc[4]={0,0,-1,1};
    // 시작칸이 통로일 때만 큐에 넣는다.
    // 시작이 벽이면 탐색하지 않고 모든 탈출구를 도달 불가능으로 둔다.
    if(g[0][0]=='1') { d[0][0]=0; q.push({0,0}); }
    // 큐 앞의 칸을 꺼내 상하좌우 이웃을 살펴본다.
    // C는 위치 p=r*m+c로 저장하며 p/m과 p%m으로 행과 열을 복원한다.
    while(!q.empty()) {
        auto [r,c]=q.front(); q.pop();
        for(int j=0;j<4;++j) {
            int nr=r+dr[j],nc=c+dc[j];
            // 배열 범위부터 검사하고 범위를 벗어나면 건너뛴다.
            // 그 뒤에만 격자와 거리표를 읽어 잘못된 위치 접근을 막는다.
            if(nr<0||nr>=n||nc<0||nc>=m) continue;
            if(g[nr][nc]=='0'||d[nr][nc]!=-1) continue;
            // 통로이며 미방문인 이웃의 거리는 현재 거리+1이다.
            // 큐에 넣기 전에 거리를 기록해 다른 칸이 같은 이웃을 중복 삽입하지 못하게 한다.
            d[nr][nc]=d[r][c]+1; q.push({nr,nc});
        }
    }
    int best=-1,idx=-1;
    // 탈출구는 입력 순서대로, 번호 1부터 확인한다.
    // 거리가 0 이상인 것만 후보이고 더 짧을 때만 교체한다.
    // 거리 동점에서는 교체하지 않아 더 작은 번호가 남는다.
    for(int i=1;i<=k;++i) {
        int r,c; cin >> r >> c;
        if(d[r][c]>=0&&(best==-1||d[r][c]<best)) // 미도달 -1을 최소 거리로 선택하지 않는다.
            { best=d[r][c]; idx=i; }
    }
    cout << idx << ' ' << best << '\n';
}

// 손으로 확인: 거리표: 0 1 2 / -1 2 -1 / 4 3 4
// 손으로 확인: 1번 거리4 → 후보
// 손으로 확인: 2번 거리2 → 교체
// 손으로 확인: 3번 거리4 → 유지
// 손으로 확인: 출력2 2
// 완성 후 확인: 좌표 0 기반과 탈출구 번호 1 기반을 구분한다.
// 완성 후 확인: 거리 -1을 최솟값으로 선택하지 않는다.
// 완성 후 확인: 시작칸도 탈출구가 될 수 있고 거리는 0.
