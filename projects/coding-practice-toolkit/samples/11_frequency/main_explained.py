# 여러 문자열에 나온 소문자의 총 횟수를 a부터 z까지 출력한다.
# 입력의 첫 정수 N은 문자열 개수이므로 문자 빈도에 포함하면 안 된다.
# 출력은 26칸을 모두 표시하며, 등장하지 않은 문자도 0을 출력한다.
# 입력 제한과 실행 비용: 전체 문자 수 S. C O(S+26), C++ map O(S log 26+26 log 26), Python dict 평균 O(S+26). 고정 알파벳 크기를 상수로 보면 모두 O(S). C 추가 공간 O(1000+26), C++ O(1000+26), Python 전체 입력 파싱 포함 O(S+N).

# C의 freq[0]은 a, freq[25]는 z의 개수다. 문자에서 a를 빼 인덱스로 바꾼다.
# C++ map과 Python dict는 문자 자체를 키로 사용하고 값에 등장 횟수를 저장한다.
# 전체 문자 수가 최대 1,000,000이며 누적 횟수를 저장한다. C/C++은 long long을 사용한다.

# sys.stdin.buffer는 입력을 바이트로 읽는다. read는 전체 입력을 메모리에 올린다는 점을 고려한다.
# 문자열이 필요하면 decode하고 숫자가 필요하면 int로 바꾼다. 정수는 큰 값도 자동 확장된다.

import sys
data=sys.stdin.buffer.read().split()
n=int(data[0])
freq={}
# N개의 문자열만 처리한다.
# 문자열마다 문자 하나씩 빈도를 늘리며 문자열이 달라도 같은 문자 카운터를 공유한다.
for token in data[1:n+1]:
    # 현재 문자열의 모든 문자에 대해 카운터를 한 번 증가시킨다.
    # 소문자 a~z라는 입력 조건 덕분에 문자 인덱스가 항상 0~25 안에 있다.
    for ch in token.decode():
        freq[ch]=freq.get(ch,0)+1 # 처음 등장한 문자는 기본값 0에 1을 더하고, 기존 문자는 누적한다.
# a~z를 직접 순서대로 방문해서 자료구조 순회 순서에 답을 맡기지 않는다.
# C++ map에서 없는 키를 []로 읽으면 0이 생성되고, Python get(키,0)은 없을 때 0을 준다.
print(' '.join(str(freq.get(chr(97+i),0)) for i in range(26)))

# 손으로 확인: aba 처리: a=2,b=1
# 손으로 확인: cab 처리: a=3,b=2,c=1
# 손으로 확인: z 처리: z=1
# 손으로 확인: 출력 시작: 3 2 1, d~y는 0, 끝 z=1
# 완성 후 확인: N을 문자열 본문으로 세지 않는다.
# 완성 후 확인: 출력 26개에는 0도 포함한다.
# 완성 후 확인: Python get(ch,0)으로 처음 등장한 문자도 처리한다.
# 완성 후 확인: C에서 문자열 끝의 널 문자를 빈도로 세지 않는다.
