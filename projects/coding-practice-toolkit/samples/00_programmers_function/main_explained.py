# PDF의 함수 예제에 독립 실행용 입력과 print를 덧붙였습니다.
# 함수는 인자를 받아 계산한 답을 반환합니다. 함수 정의만 읽었다고 함수가 자동 실행되지는 않습니다.
# 함수 정의 아래의 호출문이 계산을 시작한다.
import sys
def solution(a):
    ans = 0  # 지금까지 처리한 원소의 합입니다.
    for x in a:  # a의 원소를 하나씩 x에 넣어 반복합니다.
        ans += x  # 이전 합에 현재 값을 더합니다.
    return ans  # 호출한 쪽에 결과를 돌려줍니다. return 이후 함수의 실행이 끝납니다.
# 입력 파일을 EOF까지 읽고 공백으로 나눠 정수 목록으로 바꿉니다.
# F5의 자동 파일 입력을 사용하면 입력 끝이 명확해서 read()가 대기하지 않습니다.
data = list(map(int, sys.stdin.buffer.read().split()))
if data:
    n = data[0]  # 첫 정수는 개수입니다.
    a = data[1:1+n]  # 끝 인덱스는 포함하지 않으므로 정확히 N개를 선택합니다.
    print(solution(a))  # 함수 반환값을 받아 실제 답을 출력합니다.
# 함수 순회 O(N), 입력 목록과 슬라이스 저장 O(N). N=0이면 ans=0을 그대로 반환합니다.
