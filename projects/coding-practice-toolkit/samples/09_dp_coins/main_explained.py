# 자체 창작 연습 09 · 최소 동전 개수 
# 핵심 상태: dp[x]는 금액 x를 만드는 최소 동전 개수. inf는 만들 수 없음, dp[0]=0이다.
# Python 3: 파일의 위에서 아래로 실행한다. 들여쓰기가 반복문·조건문·함수의 범위다.
# sys.stdin은 표준입력이다. read()는 EOF까지 읽으므로 파일 입력과 온라인 채점에 편하다.
# 터미널에 직접 붙여 넣을 때 read()가 대기하면 Windows에서 Ctrl+Z 후 Enter로 EOF를 보낸다.

import sys
data = list(map(int, sys.stdin.buffer.read().split()))
n, k = data[0], data[1]
coin = data[2:n + 2]
inf = 10001
# 금액 0~k까지 사용할 k+1칸을 불가능 값으로 초기화한다.
# dp[0]=0만 가능 상태로 만들면 동전 하나를 쓰는 후보를 시작할 수 있다.
# 최소 동전 개수는 최대 10000이므로 inf=10001이 충분한 구분 값이다.
dp = [inf] * (k + 1)
dp[0] = 0
# range의 끝을 포함하지 않으므로 목표 k까지 채우려면 k+1을 사용한다.
# 각 c에 대해 c<=x이면 이전 금액 x-c의 답에 1을 더한 후보를 본다.
# min은 기존 후보와 새 후보 중 작은 값을 반환해 최소 개수를 유지한다.
for x in range(1, k + 1):
    for c in coin:
        if c <= x:
            dp[x] = min(dp[x], dp[x - c] + 1)  # 이전 금액의 최솟값에 동전 하나를 추가한다.
# Python의 조건식은 참일 때 값 if 조건 else 거짓일 때 값 순서다.
# 목표가 불가능 상태면 -1, 아니면 계산된 최소 동전 개수를 출력한다.
# 정답 2와 동전 조합의 개수 2는 다른 개념이다. 이 문제는 최소 사용 개수만 묻는다.
print(-1 if dp[k] == inf else dp[k])

# 복잡도: 시간 O(NK), 공간 O(N+K).
# 마지막 경계 확인:
# - 동전은 무제한 사용 가능하다. 한 번씩만 쓰는 문제와 다르다.
# - dp를 0으로 채우면 불가능한 금액도 가능하다고 처리된다.
# - x-c가 음수인 후보는 건너뛴다.
# - INF=K+1도 가능하지만 여기서는 제한에 맞춰 10001을 쓴다.
