# 두 종류 괄호는 개수뿐 아니라 종류와 닫히는 순서도 맞아야 한다.
# 스택의 맨 위는 가장 최근에 열린, 다음에 닫혀야 할 괄호다.
# 한 문자씩 처리하고 첫 불일치를 발견하면 바로 검사에 실패한다.
# 입력 제한과 실행 비용: 시간 O(S), 공간 O(S).

# st는 아직 닫히지 않은 여는 괄호들을 순서대로 담는다.
# C의 top은 담긴 괄호 수이자 다음에 넣을 위치다. 맨 위는 top-1에 있다.
# ok는 지금까지 규칙을 지켰는지 나타낸다. wanted는 현재 닫는 괄호에 맞는 여는 괄호다.

# sys.stdin.buffer는 입력을 바이트로 읽는다. read는 전체 입력을 메모리에 올린다는 점을 고려한다.
# 문자열이 필요하면 decode하고 숫자가 필요하면 int로 바꾼다. 정수는 큰 값도 자동 확장된다.

import sys
s=sys.stdin.buffer.read().strip().decode()
st=[]
ok=True
# 여는 괄호는 그대로 스택에 넣고 닫는 괄호는 맨 위와 짝을 맞춘다.
# 전체 길이만큼 한 번 읽으므로 시간 O(S), 최대 스택 크기도 O(S)다.
for ch in s:
    if ch in '([': st.append(ch)
    else:
        wanted='(' if ch==')' else '[' # 닫는 )에는 (, 닫는 ]에는 [가 필요하다.
        # 빈 스택인지 먼저 검사한 뒤에만 맨 위를 읽는다.
        # C/C++의 ||와 Python의 or는 앞 조건이 참이면 뒤 조건을 읽지 않는 단락 평가를 한다.
        # 종류가 다르면 올바르지 않다. 단순 개수만으로는 ([)]를 거를 수 없다.
        if not st or st[-1]!=wanted:
            ok=False
            break
        # 짝이 맞으면 맨 위 여는 괄호를 제거한다.
        # 이후에는 그보다 먼저 열렸던 괄호가 맨 위가 된다.
        st.pop()
# 문자열을 다 읽었어도 여는 괄호가 남아 있으면 실패다.
# 예를 들어 [[는 중간 불일치가 없어도 끝에서 스택이 비지 않는다.
if st: ok=False
print('YES' if ok else 'NO')

