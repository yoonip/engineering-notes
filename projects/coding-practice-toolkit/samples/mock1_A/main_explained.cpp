// 관측값을 값별로 세고, 기준 횟수 이상 나온 서로 다른 값만 고른다.
// 관측값은 0~1000이므로 값 자체를 배열 위치로 사용할 수 있다.
// 개수는 조건을 만족한 값의 종류 수이며, 그 값들이 나타난 총 횟수가 아니다.
// 입력 제한과 실행 비용: 시간 O(N+1001). C/C++ 공간 O(1001), Python 전체 파싱 포함 O(N+1001).

// freq[x]는 값 x가 나온 횟수다. 처음에는 모든 칸이 0이어야 한다.
// count는 선택한 종류 수, smallest는 처음 선택한 값이며 -1은 아직 없다는 표시다.
// Python의 values는 작은 값부터 담긴 결과 목록으로 두 상태를 대신 표현한다.

// vector는 실행 중 정해진 크기의 배열, queue는 먼저 넣은 원소를 먼저 꺼내는 큐다.
// 사용한 컨테이너와 헤더는 이 원문 그대로 따른다. 빠른 cin 설정 뒤에는 scanf와 섞지 않는다.

#include <iostream>
using namespace std;
int main() {
    ios::sync_with_stdio(false); cin.tie(nullptr);
    int n,r,x,count=0,smallest=-1,freq[1001]={};
    cin >> n >> r;
    // 입력 개수 N만큼 빈도표를 채운다.
    // 값 x를 읽을 때 freq[x]를 한 번 증가시키므로 중복도 정확히 누적된다.
    for (int i=0; i<n; ++i) { cin >> x; ++freq[x]; }
    // 0부터 1000까지 작은 값부터 확인한다.
    // freq[x] >= r이므로 기준과 같은 횟수도 포함한다.
    // 첫 선택을 그대로 유지하면 최솟값을 따로 정렬할 필요가 없다.
    for (int x=0; x<=1000; ++x) if (freq[x]>=r) {
        ++count;
        if (smallest==-1) smallest=x; // 이미 찾은 최솟값을 뒤의 큰 값으로 덮어쓰지 않는다.
    }
    // 선택한 값이 없으면 종류 수 0과 최솟값 -1을 출력한다.
    // 빈 목록에서 values[0]을 바로 읽지 않도록 Python은 조건식을 사용한다.
    cout << count << ' ' << smallest << '\n';
}

// 손으로 확인: 1→3회, 2→1회, 3→3회
// 손으로 확인: R=2 이상인 값은 {1,3}
