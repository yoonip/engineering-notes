def solution(lottos, win_nums):
    matched = 0
    unknown = lottos.count(0)

    for number in lottos:
        if number in win_nums:
            matched += 1

    best_rank = min(6, 7 - (matched + unknown))
    worst_rank = min(6, 7 - matched)

    return [best_rank, worst_rank]


