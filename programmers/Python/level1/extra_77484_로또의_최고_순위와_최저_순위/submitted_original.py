# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# lottos.count(0)은 리스트에서 정수 0이 몇 개 있는지 구함.
# 예: [44, 1, 0, 0, 31, 25].count(0) → 2
# 여기서는 정수 목록이므로 문자 "0"이 아닌 정수 0을 사용함.
#
# number in win_nums는 해당 번호가 당첨 번호 목록에 있는지 확인함.
# 번호의 위치나 순서는 상관없고, 같은 값이 있으면 맞은 것으로 셈.
# 당첨 번호에는 0이 없으므로, 지워진 번호는 matched에 포함되지 않음.
#
# 최고로 많이 맞는 개수 = 확실히 맞은 개수 + 지워진 번호 개수
# 최저로 적게 맞는 개수 = 확실히 맞은 개수
#
# 이 문제의 순위 규칙:
# 6개 일치 → 1등
# 5개 일치 → 2등
# 4개 일치 → 3등
# 3개 일치 → 4등
# 2개 일치 → 5등
# 1개 또는 0개 일치 → 6등
#
# 기본적으로 7 - 맞은 개수로 순위를 계산할 수 있음.
# 예: 4개가 맞으면 7 - 4 = 3등.
#
# 하지만 0개가 맞으면 7 - 0 = 7이 되므로 보정이 필요함.
# min(6, 계산한 순위)는 두 값 중 작은 값을 골라 최대 6등으로 제한함.
# 예: min(6, 3) → 3등, min(6, 7) → 6등.
#
# 순위를 나타내는 숫자는 작을수록 좋은 순위임.
# 따라서 최고 순위가 3등, 최저 순위가 5등이면 [3, 5]를 반환함.
#
# ------------------------------------------------------------
# 예제: lottos = [44, 1, 0, 0, 31, 25]
#       win_nums = [31, 10, 45, 1, 6, 19]
# ------------------------------------------------------------
# 확실히 맞은 번호: 1, 31 → matched = 2
# 지워진 번호: 0 두 개 → unknown = 2
#
# 최고: 지워진 두 번호도 모두 맞는다고 가정
# 맞은 개수 = 2 + 2 = 4개 → 3등
#
# 최저: 지워진 두 번호가 모두 틀린다고 가정
# 맞은 개수 = 2개 → 5등
#
# 최종 반환값: [3, 5]
#
# 모든 번호가 0이라면 최고 6개, 최저 0개 일치 → [1, 6]
# 지워진 번호 없이 모두 맞았다면 최고·최저 모두 6개 일치 → [1, 1]