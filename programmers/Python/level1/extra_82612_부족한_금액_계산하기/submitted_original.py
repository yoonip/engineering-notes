# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# 매번 같은 이용료를 내는 것이 아니라, 이용하는 회차에 비례해서 요금이 증가함.
# 1회차: price × 1
# 2회차: price × 2
# 3회차: price × 3
# ...
# count회차: price × count
#
# 따라서 총이용료는 다음과 같음.
# total = price × (1 + 2 + 3 + ... + count)
#
# 1부터 count까지의 합은 count × (count + 1) ÷ 2로 구할 수 있음.
# 예: 1 + 2 + 3 + 4 = 4 × 5 ÷ 2 = 10
# 이 공식을 사용해서 반복문 없이 전체 이용료를 계산함.
#
# //는 나눗셈 결과를 내림해서 구하는 연산자.
# 여기서는 count와 count + 1 중 하나가 짝수이므로 2로 정확히 나누어떨어짐.
# 따라서 // 2로 소수점 없는 정수 금액을 얻을 수 있음.
#
# total - money는 총이용료에서 현재 가진 돈을 뺀 값.
# 양수이면 그만큼 돈이 부족하고, 0 이하이면 돈이 충분함.
#
# max(a, b)는 두 값 중 큰 값을 선택함.
# max(0, 10)  → 10: 10원이 부족함.
# max(0, 0)   → 0: 돈이 정확히 맞음.
# max(0, -10) → 0: 돈이 10원 남으므로 부족한 금액은 0.
#
# ------------------------------------------------------------
# 예제: price = 3, money = 20, count = 4
# ------------------------------------------------------------
# 1회차 이용료: 3 × 1 = 3
# 2회차 이용료: 3 × 2 = 6
# 3회차 이용료: 3 × 3 = 9
# 4회차 이용료: 3 × 4 = 12
#
# 총이용료: 3 + 6 + 9 + 12 = 30
# 공식으로 계산: 3 × 4 × 5 ÷ 2 = 30
#
# 가진 돈: 20
# 부족한 금액: 30 - 20 = 10
# 최종 반환값: 10