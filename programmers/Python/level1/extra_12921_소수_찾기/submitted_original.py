def solution(n):
    is_prime = [True] * (n + 1)
    is_prime[0] = False
    is_prime[1] = False

    number = 2

    while number * number <= n:
        if is_prime[number]:
            for multiple in range(number * number, n + 1, number):
                is_prime[multiple] = False

        number += 1

    return sum(is_prime)


