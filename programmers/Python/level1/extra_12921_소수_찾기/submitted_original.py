# 소수는 1보다 큰 자연수 중 1과 자기 자신으로만 나누어떨어지는 수.
# 예: 2, 3, 5, 7은 소수. 1은 소수가 아님.
#
# is_prime은 숫자별로 소수 여부를 기록하는 리스트.
# is_prime[5]는 숫자 5의 상태, is_prime[10]은 숫자 10의 상태를 나타냄.
# 처음의 True는 '아직 제외하지 않은 후보'라는 뜻.
# 배수들을 모두 제외하고 나면 True인 위치가 실제 소수에 해당함.
#
# [True] * (n + 1)은 True를 n + 1개 넣은 리스트를 만듦.
# 리스트 위치는 0부터 시작하므로, n번 위치까지 쓰려면 n + 1칸이 필요함.
# 예: n = 5이면 위치 0, 1, 2, 3, 4, 5를 사용하므로 총 6칸.
#
# is_prime[multiple] = False는 리스트 원소를 삭제하는 것이 아님.
# 해당 위치의 표시만 False로 바꿔 숫자와 리스트 위치의 대응을 유지함.
#
# range(시작, 끝, 간격)은 끝값을 포함하지 않음.
# 따라서 n까지 확인하려면 끝값에 n + 1을 넣어야 함.
#
# 예: number = 2, n = 10
# range(4, 11, 2) → 4, 6, 8, 10
# 이 숫자들은 2의 배수이므로 모두 False로 바꿈.
# 2 자신은 소수이므로 제외하지 않음.
#
# number * number부터 시작하는 이유:
# 그보다 작은 배수들은 이미 더 작은 소수의 배수로 처리되었기 때문.
# 예: number = 3이면 6은 이미 2의 배수로 제외했으므로 9부터 시작.
# 예: number = 5이면 10, 15, 20은 이미 처리했으므로 25부터 시작.
#
# number * number <= n까지만 확인하는 이유:
# 소수가 아닌 수는 반드시 제곱근 이하의 약수를 하나 이상 가짐.
# 따라서 그 범위의 소수들로 배수를 제거하면 나머지는 소수만 남음.
# 모든 숫자를 n까지 확인하면서 배수를 지울 필요가 없음.
#
# number += 1은 if 바깥이지만 while 안에 있음.
# 현재 숫자가 소수든 아니든 다음 숫자로 넘어가야 하기 때문.
#
# sum(is_prime)은 리스트의 값을 모두 더함.
# 파이썬에서 True는 1, False는 0처럼 계산됨.
# 예: sum([False, False, True, True, False]) → 2
#
