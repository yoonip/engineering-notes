# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# min(a, b)는 두 값 중 작은 값을 선택함.
#
# n - m + 1은 롤러를 놓을 수 있는 가장 오른쪽 시작 위치.
# 예: 벽 길이 n = 8, 롤러 길이 m = 4라면 시작 위치는 최대 5.
# 5번에서 시작하면 5, 6, 7, 8번을 칠하므로 벽 밖으로 나가지 않음.
#
# start + m - 1에서 1을 빼는 이유는 시작 구역도 한 칸으로 세기 때문.
# 예: 2번부터 4칸을 칠하면 2, 3, 4, 5번 → 마지막은 2 + 4 - 1 = 5.
#
# position <= painted_until이면 이미 칠한 구역이므로 아무것도 하지 않음.
# if 조건이 거짓이면 다음 반복으로 넘어가므로 별도의 else가 필요 없음.
#
# ------------------------------------------------------------
# 예제: n = 8, m = 4, section = [2, 3, 6]
# ------------------------------------------------------------
# 2번 확인: 아직 안 칠함 → 2~5번을 칠함 → answer = 1
# 3번 확인: 이미 2~5번 범위에 포함됨 → 건너뜀
# 6번 확인: 아직 안 칠함 → 벽 끝에 맞춰 5~8번을 칠함 → answer = 2
#
# 5번을 다시 칠해도 괜찮음. 이미 칠한 구역과 겹치는 것은 허용됨.
# 최종 반환값: 2