# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. min(arr)
#
# 리스트에서 가장 작은 숫자를 찾는 함수.
#
# arr = [4, 3, 2, 1]
# min(arr) → 1
#
# ------------------------------------------------------------
# 2. arr.remove(min(arr))
#
# remove()는 리스트에서 지정한 값을 제거함.
#
# arr = [4, 3, 2, 1]
# arr.remove(1)
#
# 결과: [4, 3, 2]
#
# remove(1)은 값 1을 제거함.
# pop(1)은 인덱스 1에 있는 원소를 제거함.
# 두 명령어의 의미가 다르므로 주의.
#
# remove()는 원본 리스트를 직접 변경함.
# 따라서 arr = arr.remove(1)처럼 쓰면 안 됨.
#
# ------------------------------------------------------------
# 3. if len(arr) == 0:
#
# len(arr)는 리스트 안의 원소 개수를 구함.
# ==는 두 값이 같은지 비교함.
#
# 예: arr = []
# len(arr) → 0
#
# 따라서 리스트가 비었는지 확인하는 조건.
#
# ------------------------------------------------------------
# 4. return [-1]
#
# [-1]은 정수 -1이 들어 있는 리스트.
#
# return -1   → 정수를 반환
# return [-1] → 리스트를 반환
#
# 문제에서는 배열을 반환해야 하므로 [-1]을 사용함.
#
# ------------------------------------------------------------
# 5. return arr
#
# 가장 작은 숫자를 제거한 최종 리스트를 반환함.
#
# if문에서 return [-1]이 실행되면 함수가 끝나므로
# 그 아래의 return arr는 실행되지 않음.
#
# ------------------------------------------------------------
# 예제 1: arr = [4, 3, 2, 1]
