def solution(h1, m1, s1, h2, m2, s2):
    start = h1 * 3600 + m1 * 60 + s1
    end = h2 * 3600 + m2 * 60 + s2
    def count(t):
        return t * 719 // 43200 + t * 59 // 3600 - t // 43200 + 1
    at_start = start * 719 % 43200 == 0 or start * 59 % 3600 == 0
    return count(end) - count(start) + int(at_start)

