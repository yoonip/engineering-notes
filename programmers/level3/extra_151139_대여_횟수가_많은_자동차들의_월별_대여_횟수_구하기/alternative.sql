-- 먼저 월별 기록 수를 만든 후 차량별 합을 윈도 함수로 구해 5회 이상만 남깁니다.
WITH monthly AS (
 SELECT MONTH(START_DATE) AS MONTH,CAR_ID,COUNT(*) AS RECORDS
 FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
 WHERE START_DATE>='2022-08-01' AND START_DATE<'2022-11-01'
 GROUP BY MONTH(START_DATE),CAR_ID
), totals AS (SELECT monthly.*,SUM(RECORDS) OVER(PARTITION BY CAR_ID) AS TOTAL FROM monthly)
SELECT MONTH,CAR_ID,RECORDS FROM totals WHERE TOTAL>=5 ORDER BY MONTH,CAR_ID DESC;
