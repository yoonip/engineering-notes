-- 기간 내 판매량을 도서별로 먼저 합친 뒤 카테고리별로 다시 합칩니다.
WITH sales AS (
 SELECT BOOK_ID,SUM(SALES) AS SALES FROM BOOK_SALES
 WHERE SALES_DATE>='2022-01-01' AND SALES_DATE<'2022-02-01' GROUP BY BOOK_ID
)
SELECT b.CATEGORY,SUM(s.SALES) AS TOTAL_SALES
FROM BOOK b JOIN sales s ON b.BOOK_ID=s.BOOK_ID
GROUP BY b.CATEGORY ORDER BY b.CATEGORY;
