-- 차량 목록마다 기준일이 포함되는 대여 구간의 존재를 검사합니다. 양 끝 날짜를 모두 포함합니다.
SELECT c.CAR_ID,
 CASE WHEN EXISTS (SELECT 1 FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY h
 WHERE h.CAR_ID=c.CAR_ID AND h.START_DATE<='2022-10-16' AND h.END_DATE>='2022-10-16')
 THEN '대여중' ELSE '대여 가능' END AS AVAILABILITY
FROM (SELECT DISTINCT CAR_ID FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY) c
ORDER BY c.CAR_ID DESC;
