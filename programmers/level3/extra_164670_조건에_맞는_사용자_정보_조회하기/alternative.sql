-- 3개 이상 작성한 사용자 집계를 먼저 만들고 사용자 테이블에 조인합니다.
SELECT u.USER_ID,u.NICKNAME,
       CONCAT_WS(' ',u.CITY,u.STREET_ADDRESS1,u.STREET_ADDRESS2) AS `전체주소`,
       CONCAT(LEFT(u.TLNO,3),'-',SUBSTRING(u.TLNO,4,4),'-',RIGHT(u.TLNO,4)) AS `전화번호`
FROM USED_GOODS_USER AS u
JOIN (SELECT WRITER_ID FROM USED_GOODS_BOARD GROUP BY WRITER_ID HAVING COUNT(*)>=3) AS b
ON b.WRITER_ID=u.USER_ID ORDER BY u.USER_ID DESC;
