-- 완료된 거래만 사용자별로 먼저 합산해 조인 중간 행을 줄입니다.
WITH sales AS (
    SELECT WRITER_ID,SUM(PRICE) AS TOTAL_SALES FROM USED_GOODS_BOARD
    WHERE STATUS='DONE' GROUP BY WRITER_ID HAVING SUM(PRICE)>=700000
)
SELECT u.USER_ID,u.NICKNAME,s.TOTAL_SALES
FROM USED_GOODS_USER u JOIN sales s ON s.WRITER_ID=u.USER_ID
ORDER BY s.TOTAL_SALES;
