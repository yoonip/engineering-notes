-- 입양 시각에서 입소 시각을 뺀 보호 기간으로 순위를 매겨 상위 두 행을 고릅니다.
WITH ranked AS (
 SELECT i.ANIMAL_ID,i.NAME,ROW_NUMBER() OVER(ORDER BY TIMESTAMPDIFF(SECOND,i.DATETIME,o.DATETIME) DESC) AS RN
 FROM ANIMAL_INS i JOIN ANIMAL_OUTS o ON i.ANIMAL_ID=o.ANIMAL_ID
)
SELECT ANIMAL_ID,NAME FROM ranked WHERE RN<=2 ORDER BY RN;
