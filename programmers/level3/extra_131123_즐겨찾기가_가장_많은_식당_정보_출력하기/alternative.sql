-- 음식 종류마다 즐겨찾기 내림차순 순위를 매기고 공동 1위까지 남깁니다.
WITH ranked AS (
 SELECT FOOD_TYPE,REST_ID,REST_NAME,FAVORITES,
 DENSE_RANK() OVER(PARTITION BY FOOD_TYPE ORDER BY FAVORITES DESC) AS RANKING FROM REST_INFO
)
SELECT FOOD_TYPE,REST_ID,REST_NAME,FAVORITES FROM ranked WHERE RANKING=1
ORDER BY FOOD_TYPE DESC;
