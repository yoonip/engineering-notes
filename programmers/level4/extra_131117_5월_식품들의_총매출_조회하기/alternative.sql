-- 월 생산량을 상품별로 먼저 합산한 뒤 단가를 한 번 곱합니다.
WITH quantities AS (SELECT PRODUCT_ID,SUM(AMOUNT) AS total FROM FOOD_ORDER WHERE PRODUCE_DATE>='2022-05-01' AND PRODUCE_DATE<'2022-06-01' GROUP BY PRODUCT_ID)
SELECT p.PRODUCT_ID,p.PRODUCT_NAME,p.PRICE*q.total AS TOTAL_SALES FROM FOOD_PRODUCT p JOIN quantities q ON p.PRODUCT_ID=q.PRODUCT_ID
ORDER BY TOTAL_SALES DESC,p.PRODUCT_ID;
