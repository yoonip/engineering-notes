-- 리뷰 평균을 별도 CTE에서 계산하고 서울 식당에 조인합니다.
WITH scores AS (SELECT REST_ID,ROUND(AVG(REVIEW_SCORE),2) AS SCORE FROM REST_REVIEW GROUP BY REST_ID)
SELECT i.REST_ID,i.REST_NAME,i.FOOD_TYPE,i.FAVORITES,i.ADDRESS,s.SCORE
FROM REST_INFO i JOIN scores s ON s.REST_ID=i.REST_ID WHERE i.ADDRESS LIKE '서울%'
ORDER BY s.SCORE DESC,i.FAVORITES DESC;
