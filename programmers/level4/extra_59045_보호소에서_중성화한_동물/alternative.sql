-- 입양 기록을 상관 EXISTS로 검사해 입소 정보만 출력합니다.
SELECT i.ANIMAL_ID,i.ANIMAL_TYPE,i.NAME FROM ANIMAL_INS i
WHERE i.SEX_UPON_INTAKE LIKE 'Intact%' AND EXISTS (
 SELECT 1 FROM ANIMAL_OUTS o WHERE o.ANIMAL_ID=i.ANIMAL_ID AND (o.SEX_UPON_OUTCOME LIKE 'Neutered%' OR o.SEX_UPON_OUTCOME LIKE 'Spayed%')
) ORDER BY i.ANIMAL_ID;
