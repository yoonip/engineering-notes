-- DENSE_RANK로 회원별 리뷰 수 순위를 매긴 뒤 1위 회원들의 리뷰를 조인합니다.
WITH counts AS (SELECT MEMBER_ID,COUNT(*) AS cnt FROM REST_REVIEW GROUP BY MEMBER_ID),
ranked AS (SELECT MEMBER_ID,DENSE_RANK() OVER(ORDER BY cnt DESC) AS ranking FROM counts)
SELECT m.MEMBER_NAME,r.REVIEW_TEXT,DATE_FORMAT(r.REVIEW_DATE,'%Y-%m-%d') AS REVIEW_DATE
FROM REST_REVIEW r JOIN MEMBER_PROFILE m ON m.MEMBER_ID=r.MEMBER_ID
JOIN ranked c ON c.MEMBER_ID=r.MEMBER_ID WHERE c.ranking=1 ORDER BY r.REVIEW_DATE,r.REVIEW_TEXT;
