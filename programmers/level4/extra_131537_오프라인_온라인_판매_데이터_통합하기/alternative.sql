-- 전체 판매를 먼저 하나의 CTE로 통합한 뒤 바깥에서 기간 조건과 날짜 형식을 적용합니다.
WITH sales AS (
 SELECT SALES_DATE,PRODUCT_ID,USER_ID,SALES_AMOUNT FROM ONLINE_SALE
 UNION ALL SELECT SALES_DATE,PRODUCT_ID,NULL,SALES_AMOUNT FROM OFFLINE_SALE
)
SELECT DATE_FORMAT(SALES_DATE,'%Y-%m-%d') AS SALES_DATE,PRODUCT_ID,USER_ID,SALES_AMOUNT FROM sales
WHERE SALES_DATE>='2022-03-01' AND SALES_DATE<'2022-04-01' ORDER BY SALES_DATE,PRODUCT_ID,USER_ID;
