-- 각 기록에 적용 가능한 할인율을 상관 하위쿼리로 조회합니다. 할인 조인 대신 독립 조회를 써 조건을 분리합니다.
WITH rentals AS (
 SELECT h.HISTORY_ID,c.CAR_TYPE,c.DAILY_FEE,DATEDIFF(h.END_DATE,h.START_DATE)+1 AS days
 FROM CAR_RENTAL_COMPANY_CAR c JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY h ON c.CAR_ID=h.CAR_ID WHERE c.CAR_TYPE='트럭'
)
SELECT r.HISTORY_ID,FLOOR(r.DAILY_FEE*r.days*(100-COALESCE((
 SELECT p.DISCOUNT_RATE FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN p WHERE p.CAR_TYPE=r.CAR_TYPE
 AND p.DURATION_TYPE=CASE WHEN r.days>=90 THEN '90일 이상' WHEN r.days>=30 THEN '30일 이상' WHEN r.days>=7 THEN '7일 이상' END
),0))/100) AS FEE FROM rentals r ORDER BY FEE DESC,r.HISTORY_ID DESC;
