-- 십의 자리·일의 자리 숫자 조합으로 24시간을 만든 후 미리 집계한 입양 수와 합칩니다.
WITH digits AS (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9),
hours AS (SELECT 10*a.n+b.n AS hour FROM digits a CROSS JOIN digits b WHERE 10*a.n+b.n<24),
counts AS (SELECT HOUR(DATETIME) AS hour,COUNT(*) AS cnt FROM ANIMAL_OUTS GROUP BY HOUR(DATETIME))
SELECT h.hour AS HOUR,COALESCE(c.cnt,0) AS COUNT FROM hours h LEFT JOIN counts c ON c.hour=h.hour ORDER BY h.hour;
