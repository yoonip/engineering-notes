-- 판매를 도서별로 먼저 합산해 같은 책의 여러 날짜 기록을 줄인 후 조인합니다.
WITH sales AS (SELECT BOOK_ID,SUM(SALES) AS quantity FROM BOOK_SALES WHERE SALES_DATE>='2022-01-01' AND SALES_DATE<'2022-02-01' GROUP BY BOOK_ID)
SELECT a.AUTHOR_ID,a.AUTHOR_NAME,b.CATEGORY,SUM(s.quantity*b.PRICE) AS TOTAL_SALES
FROM sales s JOIN BOOK b ON s.BOOK_ID=b.BOOK_ID JOIN AUTHOR a ON a.AUTHOR_ID=b.AUTHOR_ID
GROUP BY a.AUTHOR_ID,a.AUTHOR_NAME,b.CATEGORY ORDER BY a.AUTHOR_ID,b.CATEGORY DESC;
