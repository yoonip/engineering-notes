-- 회원·년·월의 중복을 먼저 제거한 CTE에서 일반 COUNT를 구합니다.
WITH buyers AS (
 SELECT DISTINCT YEAR(s.SALES_DATE) AS YEAR,MONTH(s.SALES_DATE) AS MONTH,u.GENDER,s.USER_ID
 FROM ONLINE_SALE s JOIN USER_INFO u ON s.USER_ID=u.USER_ID WHERE u.GENDER IS NOT NULL
)
SELECT YEAR,MONTH,GENDER,COUNT(*) AS USERS FROM buyers GROUP BY YEAR,MONTH,GENDER ORDER BY YEAR,MONTH,GENDER;
