-- 겹치는 기록만 LEFT JOIN한 뒤 NULL인 행을 남기는 반조인을 사용합니다.
WITH eligible AS (
 SELECT c.CAR_ID,c.CAR_TYPE,FLOOR(c.DAILY_FEE*30*(100-p.DISCOUNT_RATE)/100) AS FEE
 FROM CAR_RENTAL_COMPANY_CAR c JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN p ON p.CAR_TYPE=c.CAR_TYPE AND p.DURATION_TYPE='30일 이상'
 LEFT JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY h ON h.CAR_ID=c.CAR_ID AND h.START_DATE<='2022-11-30' AND h.END_DATE>='2022-11-01'
 WHERE c.CAR_TYPE IN('세단','SUV') AND h.HISTORY_ID IS NULL
)
SELECT CAR_ID,CAR_TYPE,FEE FROM eligible WHERE FEE>=500000 AND FEE<2000000 ORDER BY FEE DESC,CAR_TYPE,CAR_ID DESC;
