-- 분류별 가격 순위를 DENSE_RANK로 붙여 1위만 남깁니다.
WITH ranked AS (
 SELECT CATEGORY,PRICE,PRODUCT_NAME,DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS ranking
 FROM FOOD_PRODUCT WHERE CATEGORY IN('과자','국','김치','식용유')
)
SELECT CATEGORY,PRICE AS MAX_PRICE,PRODUCT_NAME FROM ranked WHERE ranking=1 ORDER BY PRICE DESC;
