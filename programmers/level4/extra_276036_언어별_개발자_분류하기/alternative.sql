-- 통합 비트마스크 대신 EXISTS로 각 기술 조건을 직접 확인합니다. 기술 행이 여러 개 있어도 개발자 행이 늘어나지 않습니다.
WITH flags AS (
 SELECT d.ID,d.EMAIL,
 EXISTS(SELECT 1 FROM SKILLCODES s WHERE s.CATEGORY='Front End' AND (d.SKILL_CODE&s.CODE)>0) AS front,
 EXISTS(SELECT 1 FROM SKILLCODES s WHERE s.NAME='Python' AND (d.SKILL_CODE&s.CODE)>0) AS python,
 EXISTS(SELECT 1 FROM SKILLCODES s WHERE s.NAME='C#' AND (d.SKILL_CODE&s.CODE)>0) AS csharp
 FROM DEVELOPERS d
), classified AS (SELECT CASE WHEN front AND python THEN 'A' WHEN csharp THEN 'B' WHEN front THEN 'C' END AS GRADE,ID,EMAIL FROM flags)
SELECT GRADE,ID,EMAIL FROM classified WHERE GRADE IS NOT NULL ORDER BY GRADE,ID;
