def solution(sizes):  # 명함들의 가로·세로 리스트를 받음
    max_width = 0  # 지금까지 확인한 가로의 최댓값
    max_height = 0  # 지금까지 확인한 세로의 최댓값

    for width, height in sizes:  # 명함 하나의 두 길이를 꺼냄
        long_side = max(width, height)  # 두 길이 중 큰 값
        short_side = min(width, height)  # 두 길이 중 작은 값

        if long_side > max_width:  # 지금까지의 가로보다 길면
            max_width = long_side  # 새로운 가로 최댓값으로 저장

        if short_side > max_height:  # 지금까지의 세로보다 길면
            max_height = short_side  # 새로운 세로 최댓값으로 저장

    return max_width * max_height  # 가로 × 세로 반환








