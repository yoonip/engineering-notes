# 최종 반환값: [0, 0, 2, 1]
#
# 주의: 뒤집은 문자열 전체를 int("0021")로 변환하면
# 21이 되어 앞의 0들이 사라짐.
# 따라서 각 글자를 개별적으로 정수로 변환해야 함.