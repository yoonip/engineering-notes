# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. str(n)
#
# str()은 숫자를 문자열로 변환하는 함수.
#
# 예: n = 12345
#
# str(n) → "12345"
#
# 12345는 정수이고, "12345"는 문자열임.
# 문자열로 바꾸면 각 자리의 숫자를 글자처럼 하나씩 꺼낼 수 있음.
#
# ------------------------------------------------------------
# 2. [::-1]
#
# 문자열이나 리스트의 순서를 뒤집는 슬라이싱 문법.
#
# 슬라이싱의 기본 형태:
# [시작:끝:간격]
#
# [::-1]은 시작과 끝을 생략하고, -1 간격으로 이동한다는 뜻.
# 따라서 마지막 원소부터 첫 번째 원소까지 역순으로 가져옴.
#
# 예: "12345"[::-1] → "54321"
#
# 예: [1, 2, 3][::-1] → [3, 2, 1]
#
# 여기서 -1은 마지막 인덱스가 아니라 이동 간격을 의미함.
#
# ------------------------------------------------------------
# 3. for digit in str(n)[::-1]:
#
# 뒤집은 문자열에서 문자를 하나씩 꺼내는 반복문.
#
# n = 12345라면:
#
# str(n) → "12345"
# str(n)[::-1] → "54321"
#
# 첫 번째 반복: digit = "5"
# 두 번째 반복: digit = "4"
# 세 번째 반복: digit = "3"
# 네 번째 반복: digit = "2"
# 다섯 번째 반복: digit = "1"
#
# digit은 반복할 때마다 현재 문자를 저장하는 변수 이름.
#
# ------------------------------------------------------------
# 4. int(digit)
#
# int()는 숫자로 이루어진 문자열을 정수로 변환함.
#
# 예: int("5") → 5
# 예: int("4") → 4
#
# 문자열 "5"와 정수 5는 서로 다른 자료형임.
#
# 문제에서는 정수들이 들어 있는 배열을 반환해야 하므로
# 반드시 int()로 변환해서 저장해야 함.
#
# ------------------------------------------------------------
# 5. answer.append(int(digit))
#
# append()는 리스트 맨 뒤에 원소 하나를 추가하는 기능.
#
# 처음: answer = []
#
# 첫 번째 반복: answer.append(5)
# 결과: [5]
#
# 두 번째 반복: answer.append(4)
# 결과: [5, 4]
#
# 세 번째 반복: answer.append(3)
# 결과: [5, 4, 3]
#
# 네 번째 반복: answer.append(2)
# 결과: [5, 4, 3, 2]
#
# 다섯 번째 반복: answer.append(1)
# 결과: [5, 4, 3, 2, 1]
#
# ------------------------------------------------------------
# 6. return answer
#
# return은 함수에서 계산한 결과를 반환함.
#
# print(answer)는 화면에 출력하는 것이고,
# return answer는 함수를 호출한 곳에 결과를 돌려주는 것임.
#
# ------------------------------------------------------------
# 예제: n = 12345
# ------------------------------------------------------------
#
# 입력받은 자연수: 12345
#
# 1단계: str(12345)
# 결과: "12345"
#
# 2단계: "12345"[::-1]
# 결과: "54321"
#
# 3단계: 각 문자를 int()로 변환
# "5" → 5
# "4" → 4
# "3" → 3
# "2" → 2
# "1" → 1
#
# 4단계: append()로 차례대로 리스트에 추가
#
# 최종 반환값: [5, 4, 3, 2, 1]
#
# ------------------------------------------------------------
# 추가 예제: n = 1200
# ------------------------------------------------------------
#
# str(n) → "1200"
