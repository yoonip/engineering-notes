def solution(n, lost, reserve):
    lost_set = set(lost)
    reserve_set = set(reserve)
    need = lost_set - reserve_set
    extra = reserve_set - lost_set

    for student in sorted(extra):
        if student - 1 in need:
            need.remove(student - 1)
        elif student + 1 in need:
            need.remove(student + 1)

    return n - len(need)


