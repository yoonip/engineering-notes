# set(리스트)는 원소를 중복 없이 보관하는 집합을 만듦.
# 예: set([2, 4]) → {2, 4}
#
# 집합에서 A - B는 숫자 뺄셈이 아니라 '차집합'.
# A에 있는 원소 중 B에도 있는 원소를 제외함.
# 예: {2, 4} - {2, 3} → {4}
#
# lost와 reserve에 동시에 있는 학생은 여벌 중 한 벌을 도난당한 경우.
# 남은 한 벌은 본인이 입으므로, 다른 사람에게 빌려줄 수 없음.
# 따라서 need와 extra 양쪽에서 모두 제외해야 함.
#
# 예: lost = [2, 4], reserve = [2, 3]
# 2번은 남은 자기 체육복을 입음.
# need = {4}, extra = {3}이므로 3번이 4번에게 빌려주면 됨.
#
# sorted(extra)는 학생 번호를 작은 값부터 정렬한 리스트를 만듦.
# 집합 자체는 번호순을 보장하지 않으므로 정렬해서 처리함.
#
# student - 1은 바로 앞 번호, student + 1은 바로 뒤 번호.
# 체육복은 바로 이웃한 학생에게만 빌려줄 수 있음.
#
# need.remove(번호)는 해당 학생을 '체육복이 필요한 학생 집합'에서 제거함.
# 이미 빌린 학생은 need에서 빠지므로 다른 학생에게 또 빌리지 않음.
#
# if와 elif를 사용하므로 앞뒤 학생 모두에게 빌려주는 일이 없음.
# 앞 학생에게 빌려줬다면 elif는 실행하지 않고 다음 여벌 학생으로 넘어감.
#
# 작은 번호부터 처리할 때는 앞 번호 학생을 먼저 도와야 함.
# 예: need = {2, 4}, extra = {3, 5}
# 3번이 2번에게, 5번이 4번에게 빌려주면 둘 다 해결됨.
# 반대로 3번이 4번에게 먼저 빌려주면, 5번은 2번에게 빌려줄 수 없음.
#
# ------------------------------------------------------------
# 예제: n = 5, lost = [2, 4], reserve = [1, 3, 5]
# ------------------------------------------------------------
# 처음: need = {2, 4}, extra = {1, 3, 5}
#
# 1번 확인: 앞 번호 0은 대상에 없음 → 뒤 번호 2에게 빌려줌
# need = {4}
#
# 3번 확인: 앞 번호 2는 이미 해결됨 → 뒤 번호 4에게 빌려줌
# need = 빈 집합
#
# 5번 확인: 앞뒤에 빌려줄 대상이 없으므로 아무것도 하지 않음.
#
# 끝까지 체육복이 없는 학생 수: len(need) = 0
# 최종 반환값: 5 - 0 = 5