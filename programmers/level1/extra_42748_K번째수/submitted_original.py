# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. for i, j, k in commands:
#
# commands 안에 들어 있는 [i, j, k]를 하나씩 꺼내는 반복문.
#
# 예: commands = [[2, 5, 3], [4, 4, 1], [1, 7, 3]]
#
# 첫 번째 반복: i = 2, j = 5, k = 3
# 두 번째 반복: i = 4, j = 4, k = 1
# 세 번째 반복: i = 1, j = 7, k = 3
#
# ------------------------------------------------------------
# 2. array[i-1:j]
#
# 파이썬에서는 리스트의 위치를 0부터 셈.
#
# 예: array = [1, 5, 2, 6, 3, 7, 4]
#
# 사람이 세는 위치:  1  2  3  4  5  6  7
# 파이썬 인덱스:      0  1  2  3  4  5  6
# 실제 숫자:          1  5  2  6  3  7  4
#
# 따라서 사람이 말하는 i번째 숫자는 array[i-1]에 있음.
#
# 리스트[시작:끝]은 시작 위치부터 끝 위치 직전까지 가져옴.
#
# 예: i = 2, j = 5
# array[i-1:j] = array[1:5]
# 결과: [5, 2, 6, 3]
#
# 끝값 j에 -1을 하지 않는 이유는
# 슬라이싱에서 끝 인덱스 자체는 포함되지 않기 때문.
#
# ------------------------------------------------------------
# 3. numbers.sort()
#
# sort()는 리스트 자체를 오름차순으로 정렬하는 기능.
#
# 예: numbers = [5, 2, 6, 3]
# numbers.sort()
# 결과: [2, 3, 5, 6]
#
# sort()는 기존 리스트를 직접 바꿈.
# numbers = numbers.sort()처럼 작성하면 안 됨.
# sort()의 반환값은 None이기 때문.
#
# 참고로 sorted(numbers)는 정렬된 새로운 리스트를 반환함.
#
# ------------------------------------------------------------
# 4. numbers[k-1]
#
# 정렬된 리스트에서 k번째 숫자를 가져오는 코드.
#
# 예: numbers = [2, 3, 5, 6]
# k = 3
#
# numbers[k-1] = numbers[2] = 5
#
# 사람이 세는 3번째는 파이썬에서 인덱스 2이기 때문에
# 반드시 k - 1을 사용해야 함.
#
# ------------------------------------------------------------
# 5. answer.append()
#
# append()는 리스트 맨 뒤에 원소를 하나 추가함.
#
# answer = []
# answer.append(5)  → [5]
# answer.append(6)  → [5, 6]
# answer.append(3)  → [5, 6, 3]
#
# ------------------------------------------------------------
# 예제
# ------------------------------------------------------------
#
# array = [1, 5, 2, 6, 3, 7, 4]
# commands = [[2, 5, 3], [4, 4, 1], [1, 7, 3]]
#
# 첫 번째 명령 [2, 5, 3]
# 2번째부터 5번째까지 선택: [5, 2, 6, 3]
# 오름차순 정렬: [2, 3, 5, 6]
