def solution(array, commands):
    answer = []

    for command in commands:  # 명령을 하나씩 꺼냄
        start = command[0]    # 시작 번째
        end = command[1]      # 끝 번째
        k = command[2]        # 정렬 후 고를 번째

        numbers = []  # 이번 명령에서 사용할 숫자들

        for index in range(start - 1, end):
            numbers.append(array[index])  # 필요한 숫자를 하나씩 담기

        numbers.sort()  # 작은 순서로 정렬

        number = numbers[k - 1]  # k번째 숫자 꺼내기
        answer.append(number)   # 정답에 추가

    return answer


