# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. combinations(nums, 3)
#
# nums에서 서로 다른 위치의 숫자 3개를 선택하는 모든 조합을 생성함.
#
# 예: nums = [1, 2, 3, 4]
# combinations(nums, 3)의 조합:
# (1, 2, 3)
# (1, 2, 4)
# (1, 3, 4)
# (2, 3, 4)
#
# a, b, c에는 각 조합의 숫자 3개가 차례대로 저장됨.
# (1, 2, 3)이면 a = 1, b = 2, c = 3.
#
# 같은 3개를 순서만 바꾼 경우는 별도의 조합으로 세지 않음.
# 예: (1, 2, 3)과 (3, 2, 1)은 같은 조합으로 취급함.
#
# ------------------------------------------------------------
# 2. total ** 0.5
#
# **는 거듭제곱 연산자임.
# 2 ** 3 = 8  → 2의 3제곱
# 9 ** 0.5 = 3.0  → 9의 제곱근
#
# 소수 여부는 2부터 제곱근까지만 나누어 확인하면 충분함.
# 예: 36의 제곱근은 6이므로 2~6까지만 검사하면 됨.
#
# int()는 숫자를 정수로 변환함.
# range(2, int(total ** 0.5) + 1)은 2부터 제곱근의 정수 부분까지 확인함.
# + 1을 사용하는 이유는 range의 끝값이 포함되지 않기 때문.
#
# ------------------------------------------------------------
# 3. total % i == 0
#
# %는 나눗셈의 나머지를 구하는 연산자.
# ==는 두 값이 같은지 비교하는 연산자.
#
# 예: 10 % 2 == 0 → True
# 10은 2로 나누어떨어지므로 소수가 아님.
#
# 예: 7 % 2 == 0 → False
# 7은 2로 나누어떨어지지 않음.
#
# ------------------------------------------------------------
# 4. is_prime = True / False
#
# True는 참, False는 거짓을 나타내는 불리언 값.
# 각 조합을 검사할 때마다 True로 초기화해야 함.
#
# 어떤 숫자로 나누어떨어지면 False로 바꾸고 break로 반복 종료.
# 끝까지 False로 바뀌지 않았다면 소수라는 뜻.
#
# if is_prime: 은 if is_prime == True: 와 같은 조건으로 동작함.
#
# ------------------------------------------------------------
# 예제 1: nums = [1, 2, 3, 4]
# ------------------------------------------------------------
#
# 1 + 2 + 3 = 6 → 소수 아님
# 1 + 2 + 4 = 7 → 소수
# 1 + 3 + 4 = 8 → 소수 아님
# 2 + 3 + 4 = 9 → 소수 아님
#
# 소수가 되는 조합은 1개.
# 최종 반환값: 1
#
# ------------------------------------------------------------
