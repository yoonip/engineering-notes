# score.sort()는 작은 값부터 큰 값 순서로 정렬함.
# score.sort(reverse=True)는 반대로 큰 값부터 작은 값 순서로 정렬함.
# 예: [1, 3, 2, 3] → [3, 3, 2, 1]
#
# 내림차순으로 정렬했으므로, m개씩 묶으면 각 묶음의 마지막 값이 최솟값.
# 예: [3, 3, 2, 2] 상자의 최저 점수는 마지막 값인 2.
#
# 리스트 위치는 0부터 시작하므로, 첫 상자의 마지막 위치는 m - 1.
# 예: m = 4이면 첫 상자의 위치는 0, 1, 2, 3 → 마지막 위치는 3.
#
# range(시작, 끝, 간격)은 시작부터 끝 직전까지 간격만큼 증가함.
# range(m - 1, len(score), m)은 각 상자의 마지막 위치만 차례로 꺼냄.
# 예: m = 4이고 사과가 12개라면 i는 3, 7, 11.
# 각각 0~3번, 4~7번, 8~11번 사과로 구성된 상자의 마지막 위치.
#
# answer += score[i] * m은 아래와 같은 의미.
# answer = answer + (score[i] * m)
#
# 마지막 사과 위치가 존재하는 완성된 상자만 계산하므로,
# m개를 채우지 못한 나머지 사과는 자동으로 제외됨.
# 사과가 m개보다 적으면 반복문이 실행되지 않아 0을 반환함.
#
# k는 가능한 최고 점수를 알려주는 값.
# 이 풀이에서는 실제 점수인 score만 정렬하면 되므로 k를 직접 사용하지 않음.
#
