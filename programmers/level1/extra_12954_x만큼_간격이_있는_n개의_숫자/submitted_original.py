# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. range(1, n + 1)
#
# range(시작, 끝)은 시작 숫자부터 끝 숫자 직전까지 반복함.
#
# 예: n = 5
#
# range(1, 6) → 1, 2, 3, 4, 5
#
# 파이썬의 range는 끝값을 포함하지 않으므로
# n까지 반복하려면 n + 1을 사용해야 함.
#
# ------------------------------------------------------------
# 2. for i in range(1, n + 1):
#
# for문은 반복문이며, i는 반복할 때마다 바뀌는 변수.
#
# 예: n = 3
#
# 첫 번째 반복: i = 1
# 두 번째 반복: i = 2
# 세 번째 반복: i = 3
#
# 반복 횟수는 총 3번.
#
# ------------------------------------------------------------
# 3. x * i
#
# *는 곱셈 연산자.
#
# 예: x = 4, n = 3
#
# 첫 번째 반복: 4 * 1 = 4
# 두 번째 반복: 4 * 2 = 8
# 세 번째 반복: 4 * 3 = 12
#
# 따라서 숫자 4부터 시작해서 4씩 증가하는 결과를 만듦.
#
# ------------------------------------------------------------
# 4. answer.append(x * i)
#
# append()는 리스트의 맨 뒤에 원소 하나를 추가하는 기능.
#
# 예: x = 2, n = 3
#
# 처음: answer = []
#
# i = 1 → answer.append(2 * 1)
# 결과: answer = [2]
#
# i = 2 → answer.append(2 * 2)
# 결과: answer = [2, 4]
#
# i = 3 → answer.append(2 * 3)
# 결과: answer = [2, 4, 6]
#
# ------------------------------------------------------------
# 5. return answer
#
# return은 함수에서 계산한 결과를 돌려주는 명령어.
#
# print(answer)는 화면에 결과를 출력하는 것이고,
# return answer는 함수의 결과를 호출한 곳으로 돌려주는 것.
#
# 프로그래머스에서는 문제에서 요구한 값을 return해야 함.
#
# ------------------------------------------------------------
# 예제 1: x = 2, n = 5
# ------------------------------------------------------------
#
