# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# X.count(digit)는 X에서 해당 문자가 몇 번 등장하는지 구함.
# 예: "5525".count("5") → 3
#
# min(a, b)는 두 값 중 작은 값을 선택함.
# X에 "5"가 3개, Y에 "5"가 2개라면 공통으로 사용할 수 있는 "5"는 2개.
# 따라서 min(3, 2) = 2개만 사용함.
#
# digit은 정수가 아니라 문자이므로, digit * count는 문자열 반복.
# 예: "5" * 2 → "55". 숫자 계산인 5 * 2 = 10과는 다름.
# count가 0이면 "5" * 0은 빈 문자열 ""이 됨.
#
# parts.append(값)은 리스트 맨 뒤에 값을 하나 추가함.
# "".join(parts)는 리스트 안의 문자열들을 사이에 아무것도 넣지 않고 연결함.
# 예: "".join(["55", "", "2"]) → "552"
# 빈 문자열은 이어 붙여도 결과에 영향을 주지 않음.
#
# 빈 문자열인지 먼저 확인한 뒤에 answer[0]을 읽어야 함.
# 빈 문자열에는 첫 글자가 없어서 answer[0]을 읽으면 오류가 나기 때문.
#
# 큰 숫자부터 붙였으므로 "0"으로 시작하면서 뒤에 더 큰 숫자가 나올 수는 없음.
# 따라서 첫 글자가 "0"이면 "000"처럼 0만 있는 경우라고 판단할 수 있음.
#
# 결과는 정수가 아닌 문자열로 반환해야 함.
# 매우 긴 수가 될 수 있으므로 int(answer)로 변환할 필요도 없음.
#
# ------------------------------------------------------------
# 예제: X = "5525", Y = "1255"
