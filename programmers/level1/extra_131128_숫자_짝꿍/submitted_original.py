# 숫자 "5": X에 3개, Y에 2개 → 2개 사용 → "55"
# 숫자 "2": X에 1개, Y에 1개 → 1개 사용 → "2"
# 나머지 숫자: 두 문자열에 공통으로 존재하지 않으므로 사용하지 않음.
#
# 큰 숫자부터 연결: "55" + "2" = "552"
