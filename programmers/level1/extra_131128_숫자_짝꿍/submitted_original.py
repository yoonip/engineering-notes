def solution(X, Y):
    parts = []

    for digit in "9876543210":
        count = min(X.count(digit), Y.count(digit))
        parts.append(digit * count)

    answer = "".join(parts)

    if answer == "":
        return "-1"

    if answer[0] == "0":
        return "0"

    return answer


