# 풀이 요약
# 짝수는 절반, 홀수는 3배+1로 바꾸며 횟수를 센다. 1이 되면 멈추고, 이미 500번 했는데도 1이 아니면 -1을 반환한다. 정확히 500번째에 1이 되면 다음 while 조건에서 종료돼 500이 반환된다.
