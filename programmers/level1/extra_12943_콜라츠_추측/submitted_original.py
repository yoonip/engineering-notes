# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. while num != 1:
#
# while은 조건이 참인 동안 반복하는 반복문.
#
# != 는 '같지 않다'는 비교 연산자.
#
# num = 6이면 6 != 1 → True이므로 반복 실행.
# num = 1이면 1 != 1 → False이므로 반복 종료.
#
# 처음부터 num = 1이면 while문을 한 번도 실행하지 않음.
# 따라서 answer의 초기값인 0을 반환함.
#
# ------------------------------------------------------------
# 2. num % 2 == 0
#
# %는 나눗셈의 나머지를 구하는 연산자.
# ==는 두 값이 같은지 비교하는 연산자.
#
# 예: 6 % 2 = 0 → 짝수
# 예: 7 % 2 = 1 → 홀수
#
# 따라서 num % 2 == 0은 짝수인지 확인하는 조건.
#
# ------------------------------------------------------------
# 3. num //= 2
#
# //는 나눗셈의 정수 몫을 구하는 연산자.
# //=는 계산한 몫을 다시 같은 변수에 저장하는 연산자.
#
# num //= 2
#
# 위 코드는 아래 코드와 같은 의미.
#
# num = num // 2
#
# 예: num = 16
# num //= 2 → num = 8
#
# 예: num = 6
# num //= 2 → num = 3
#
# ------------------------------------------------------------
# 4. num = num * 3 + 1
#
# 홀수인 경우 사용하는 계산.
#
# 예: num = 3
# num = 3 * 3 + 1
# num = 10
#
# 예: num = 5
# num = 5 * 3 + 1
# num = 16
#
# ------------------------------------------------------------
# 5. answer += 1
#
# 기존 answer 값에 1을 더해서 다시 저장함.
#
# answer += 1
#
# 아래 코드와 같은 의미.
#
# answer = answer + 1
#
# 처음 answer = 0이었다면:
#
# 첫 번째 반복 후 answer = 1
# 두 번째 반복 후 answer = 2
# 세 번째 반복 후 answer = 3
#
# ------------------------------------------------------------
# 6. if answer >= 500:
#
# >= 는 '크거나 같다'는 비교 연산자.
#
# answer가 500이라면 더 이상 작업하지 않고 -1을 반환함.
#
# 단, 정확히 500번째 작업에서 num이 1이 되었다면
# while num != 1 조건이 False가 되어 정상적으로 500을 반환함.
#
# 따라서 정확히 500번 만에 성공한 경우도 올바르게 처리함.
#
# ------------------------------------------------------------
# 예제 1: num = 6
# ------------------------------------------------------------
#
# 처음: num = 6, answer = 0
#
# 1회: 6은 짝수 → 6 // 2 = 3
# 2회: 3은 홀수 → 3 * 3 + 1 = 10
# 3회: 10은 짝수 → 10 // 2 = 5
# 4회: 5는 홀수 → 5 * 3 + 1 = 16
# 5회: 16은 짝수 → 16 // 2 = 8
# 6회: 8은 짝수 → 8 // 2 = 4
# 7회: 4는 짝수 → 4 // 2 = 2
# 8회: 2는 짝수 → 2 // 2 = 1
#
# 총 8번 만에 1이 됨.
# 최종 반환값: 8
#
# ------------------------------------------------------------
# 예제 2: num = 16
# ------------------------------------------------------------
#
# 16 → 8 → 4 → 2 → 1
#
# 총 4번 반복.
# 최종 반환값: 4
#
# ------------------------------------------------------------
# 예제 3: num = 626331
# ------------------------------------------------------------
#
# 500번 작업해도 1이 되지 않음.
# 최종 반환값: -1
#
# ------------------------------------------------------------
# 예제 4: num = 1
# ------------------------------------------------------------
#
# 시작부터 1이므로 반복문이 실행되지 않음.
# 최종 반환값: 0