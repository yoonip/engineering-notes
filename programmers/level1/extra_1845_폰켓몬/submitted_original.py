# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
#
# 1. set(nums)
#
# set()은 리스트에서 중복된 값을 제거해 집합으로 만드는 함수.
#
# 예: nums = [3, 1, 2, 3]
# set(nums) → {1, 2, 3}
#
# 3이 두 번 등장해도 하나의 종류로 계산함.
#
# ------------------------------------------------------------
# 2. len(set(nums))
#
# len()은 원소의 개수를 구하는 함수.
#
# 예: nums = [3, 1, 2, 3]
# set(nums) → {1, 2, 3}
# len(set(nums)) → 3
#
# 즉, 폰켓몬의 서로 다른 종류는 총 3개.
#
# ------------------------------------------------------------
# 3. len(nums) // 2
#
# len(nums)는 전체 폰켓몬의 마릿수를 구함.
# //는 나눗셈의 정수 몫을 구하는 연산자.
#
# 예: nums = [3, 1, 2, 3]
# len(nums) = 4
# len(nums) // 2 = 4 // 2 = 2
#
# 따라서 총 4마리 중 2마리만 선택할 수 있음.
#
# ------------------------------------------------------------
# 4. min(a, b)
#
# min()은 두 값 중 작은 값을 선택하는 함수.
#
# 예: min(3, 2) → 2
# 예: min(2, 3) → 2
#
# 서로 다른 종류가 3개라도 2마리만 가져갈 수 있다면
# 최대 2종류만 선택할 수 있음.
#
# 반대로 3마리를 가져갈 수 있어도
# 서로 다른 종류가 2개뿐이라면 최대 2종류만 선택할 수 있음.
#
# ------------------------------------------------------------
# 예제 1: nums = [3, 1, 2, 3]
# ------------------------------------------------------------
#
# 전체 폰켓몬: 4마리
# 선택 가능한 폰켓몬: 4 // 2 = 2마리
# 서로 다른 종류: {1, 2, 3} → 3종류
#
# min(3, 2) = 2
# 최종 반환값: 2
#
# ------------------------------------------------------------
# 예제 2: nums = [3, 3, 3, 2, 2, 4]
# ------------------------------------------------------------
#
# 전체 폰켓몬: 6마리
# 선택 가능한 폰켓몬: 6 // 2 = 3마리
# 서로 다른 종류: {2, 3, 4} → 3종류
#
# min(3, 3) = 3
# 최종 반환값: 3
#
# ------------------------------------------------------------
# 예제 3: nums = [3, 3, 3, 2, 2, 2]
# ------------------------------------------------------------
#
# 전체 폰켓몬: 6마리
# 선택 가능한 폰켓몬: 6 // 2 = 3마리
# 서로 다른 종류: {2, 3} → 2종류
#
# min(2, 3) = 2
# 최종 반환값: 2