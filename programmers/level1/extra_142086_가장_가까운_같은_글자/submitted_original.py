# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# enumerate("banana")는 다음처럼 위치와 글자를 함께 꺼냄.
# (0, "b"), (1, "a"), (2, "n"), (3, "a"), (4, "n"), (5, "a")
#
# char in last_position은 딕셔너리에 해당 글자라는 키가 있는지 확인함.
# 예: "a" in {"b": 0, "a": 1} → True
#
# answer.append(값)은 리스트 맨 뒤에 값을 하나 추가함.
# 예: answer가 [-1, -1]일 때 answer.append(2)를 실행하면 [-1, -1, 2].
#
# last_position[char] = i는 반드시 거리 계산이 끝난 뒤에 실행해야 함.
# 먼저 현재 위치로 바꾸면 i - i가 되어 거리가 항상 0으로 계산됨.
#
# 이 줄은 if와 else 바깥에 있으므로, 처음 나온 글자든 반복된 글자든 실행됨.
# 이미 저장된 글자는 이전 위치를 덮어써서 가장 최근 위치만 유지함.
#
# ------------------------------------------------------------
# 예제: s = "banana"
# ------------------------------------------------------------
# 위치 0, "b": 처음 등장 → -1 추가 → b의 마지막 위치를 0으로 저장
# 위치 1, "a": 처음 등장 → -1 추가 → a의 마지막 위치를 1로 저장
# 위치 2, "n": 처음 등장 → -1 추가 → n의 마지막 위치를 2로 저장
# 위치 3, "a": 이전 위치 1 → 3 - 1 = 2 추가 → a의 마지막 위치를 3으로 갱신
# 위치 4, "n": 이전 위치 2 → 4 - 2 = 2 추가 → n의 마지막 위치를 4로 갱신
# 위치 5, "a": 이전 위치 3 → 5 - 3 = 2 추가 → a의 마지막 위치를 5로 갱신
#
# 마지막 "a"는 처음 나온 위치 1이 아니라, 가장 가까운 이전 위치 3과 비교함.
