# ------------------------------------------------------------
# 헷갈리기 쉬운 부분
# ------------------------------------------------------------
# hall.append(point)는 hall의 맨 뒤에 점수를 하나 추가함.
#
# hall.sort()는 hall 자체를 오름차순으로 정렬함.
# 예: [100, 10, 20] → [10, 20, 100]
# 따라서 정렬 후 hall[0]은 항상 현재 목록에서 가장 작은 점수.
#
# hall.pop(0)은 첫 번째 원소를 제거함. 점수 0을 지우라는 뜻이 아님.
# 예: [10, 20, 100, 150]에서 hall.pop(0)을 실행하면 [20, 100, 150].
#
# 하루에 점수를 하나만 추가하므로, 정원을 초과해도 하나만 제거하면 됨.
# 가장 작은 점수를 제거하면 높은 점수 k개만 남게 됨.
#
# answer.append(hall[0])은 if 바깥에 있으므로 매일 실행됨.
# 정원 k를 채우기 전에도 그날의 최하위 점수를 기록해야 하기 때문.
#
# 같은 점수도 각각 유지해야 함.
# 예: [100, 100, 150]은 점수 3개이며, 중복이라고 하나를 없애면 안 됨.
#
# ------------------------------------------------------------
# 예제: k = 3, score = [10, 100, 20, 150, 1, 100, 200]
# 아래의 hall은 정렬과 정원 초과 처리를 모두 마친 상태.
# ------------------------------------------------------------
# 1일차: 10 추가  → hall = [10]            → 발표: 10
# 2일차: 100 추가 → hall = [10, 100]       → 발표: 10
# 3일차: 20 추가  → hall = [10, 20, 100]   → 발표: 10
# 4일차: 150 추가 → hall = [20, 100, 150]  → 발표: 20
# 5일차: 1 추가   → hall = [20, 100, 150]  → 발표: 20
